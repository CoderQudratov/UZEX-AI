@pytest.mark.parametrize(
    "case",
    GOLDEN_CASES,
    ids=[f"{c.id}-{c.category[:10].strip()}-{c.language}" for c in GOLDEN_CASES],
)
@pytest.mark.anyio
async def test_golden_case_execution(case: GoldenCase, shared_engine: QueryExecutor):
    # Category K (Privacy) and Category L (Infrastructure) have dedicated tests below
    if case.category.startswith(("CATEGORY K", "CATEGORY L")):
        return

    # 1. Language detection check
    hint = detect_language(case.question)
    if case.language == "unsupported":
        assert hint.disposition == "unsupported" or hint.language is None
    elif hint.language is not None:
        assert hint.language == case.language

    # 2. Semantic understand and answer
    transport = GoldenOracleTransport(case)
    router = SemanticRouter(shared_engine, transport, reference_date=date(2026, 11, 5))

    res = await router.answer(case.question)

    # 3. Status assertion
    assert res.status == case.expected_status, (
        f"Case {case.id} failed: got {res.status} ({res.reason}), expected {case.expected_status}. "
        f"Question: {case.question}"
    )

    # 4. Accuracy & Truthfulness verification against reference value
    if case.expected_status == "VERIFIED" and case.expected_value is not None:
        assert res.verified_result is not None
        rows = res.verified_result.rows
        assert len(rows) > 0, f"Case {case.id} returned 0 rows"
        first_row = rows[0]

        if isinstance(case.expected_value, dict):
            for k, expected_v in case.expected_value.items():
                actual_v = first_row.get(k)
                assert actual_v == expected_v, (
                    f"Case {case.id} field '{k}' mismatch: got {actual_v}, expected {expected_v}"
                )
        elif isinstance(case.expected_value, (int, Decimal)):
            metric_keys = (
                "count",
                "sum_amount",
                "avg_amount",
                "sum_volume",
                "min_amount",
                "max_amount",
            )
            matched = False
            for mk in metric_keys:
                if mk in first_row:
                    actual_v = first_row[mk]
                    assert actual_v == case.expected_value, (
                        f"Case {case.id} metric '{mk}' mismatch: got {actual_v}, expected {case.expected_value}"
                    )
                    matched = True
                    break
            assert matched, f"Case {case.id} did not find metric in row: {first_row}"

    # 5. Zero Hallucination check for non-verified results
    if case.expected_status in ("NOT_FOUND", "AMBIGUOUS", "UNSUPPORTED"):
        # The answer must be a safe standard notice, never claiming invented numbers or facts
        assert res.verified_result is None or res.verified_result.row_count == 0
        forbidden_hallucinations = ["115763", "500000", "304547938", "915688255", "LO‘HI IMPEKS"]
        for forbidden in forbidden_hallucinations:
            # Only forbidden if not part of user's own question
            if forbidden not in case.question:
                assert forbidden not in res.answer, (
                    f"Hallucination detected in {case.id}: {res.answer}"
                )


