@pytest.mark.anyio
async def test_category_f_semantic_contrasts(shared_engine: QueryExecutor):
    """Verify semantic contrasts do not collapse into identical results."""

    def get_case(cid: str) -> GoldenCase:
        return next(c for c in GOLDEN_CASES if c.id == cid)

    async def run_case(cid: str):
        c = get_case(cid)
        transport = GoldenOracleTransport(c)
        router = SemanticRouter(shared_engine, transport, reference_date=date(2026, 11, 5))
        return await router.answer(c.question)

    # Contrast 1: Seller vs Buyer
    r_f01 = await run_case("F01")
    r_f02 = await run_case("F02")
    assert (
        r_f01.verified_result.rows[0]["sum_volume"] != r_f02.verified_result.rows[0]["sum_volume"]
    )

    # Contrast 2: Before 2025 vs After 2025
    r_f03 = await run_case("F03")
    r_f04 = await run_case("F04")
    assert r_f03.verified_result.rows[0]["count"] != r_f04.verified_result.rows[0]["count"]

    # Contrast 3: More vs Less
    r_f05 = await run_case("F05")
    r_f06 = await run_case("F06")
    assert r_f05.verified_result.rows[0]["sum_volume"] > r_f06.verified_result.rows[0]["sum_volume"]

    # Contrast 4: Cancelled vs Completed
    r_f09 = await run_case("F09")
    r_f10 = await run_case("F10")
    assert r_f09.verified_result.rows[0]["count"] != r_f10.verified_result.rows[0]["count"]

    # Contrast 5: Monetary Amount vs Transaction Count
    r_f11 = await run_case("F11")
    r_f12 = await run_case("F12")
    assert r_f11.verified_result.rows[0]["sum_amount"] != r_f12.verified_result.rows[0]["count"]

    # Contrast 6: Contract vs Deal
    r_f13 = await run_case("F13")
    r_f14 = await run_case("F14")
    assert "contract_id" in r_f13.verified_result.rows[0]
    assert "deal_id" in r_f14.verified_result.rows[0]

    # Contrast 7: Before 2025 vs Through 2025 inclusive
    r_f15 = await run_case("F15")
    r_f16 = await run_case("F16")
    assert r_f15.verified_result.rows[0]["count"] < r_f16.verified_result.rows[0]["count"]


@pytest.mark.anyio
async def test_category_g_semantic_equivalence(shared_engine: QueryExecutor):
    """Verify all 5 formulations across 5 equivalence clusters produce identical numerical results."""
    clusters = [
        ("Cluster 1 (2025 count)", [f"G{i:02d}" for i in range(1, 6)], 115763, "count"),
        ("Cluster 2 (Total count)", [f"G{i:02d}" for i in range(6, 11)], 500000, "count"),
        ("Cluster 3 (Cancelled count)", [f"G{i:02d}" for i in range(11, 16)], 33719, "count"),
        ("Cluster 4 (Before 2025 count)", [f"G{i:02d}" for i in range(16, 21)], 284931, "count"),
        ("Cluster 5 (Cement 2025 count)", [f"G{i:02d}" for i in range(21, 26)], 8837, "count"),
    ]

    def get_case(cid: str) -> GoldenCase:
        return next(c for c in GOLDEN_CASES if c.id == cid)

    for cluster_name, case_ids, expected_val, metric_key in clusters:
        results = []
        for cid in case_ids:
            c = get_case(cid)
            transport = GoldenOracleTransport(c)
            router = SemanticRouter(shared_engine, transport, reference_date=date(2026, 11, 5))
            res = await router.answer(c.question)
            assert res.status == "VERIFIED", f"{cluster_name} {cid} failed: {res.status}"
            assert res.verified_result is not None
            val = res.verified_result.rows[0][metric_key]
            assert val == expected_val, f"{cluster_name} {cid} got {val}, expected {expected_val}"
            results.append(val)
        # Verify complete pairwise equality within the cluster
        assert len(set(results)) == 1, f"Results within {cluster_name} diverged: {results}"


