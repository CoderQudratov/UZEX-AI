class GoldenOracleTransport:
    """Deterministic oracle transport for test cases that route through planner."""

    def __init__(self, case: GoldenCase):
        self.case = case
        self.calls = 0

    async def generate(self, system: str, contents: str):
        self.calls += 1
        tag = self.case.oracle_tag
        if tag and ":" in tag:
            status, reason = tag.split(":", 1)
            decision = SemanticDecision(
                status=status,
                language=self.case.language,
                reason=reason,
                plan=None,
            )
        elif tag:
            plan = get_expected_plan_for_tag(tag, self.case.language)
            decision = SemanticDecision(
                status="PLAN",
                language=self.case.language,
                reason="NONE",
                plan=plan,
            )
        else:
            decision = SemanticDecision(
                status=self.case.expected_status,
                language=self.case.language,
                reason=self.case.expected_reason or "NONE",
                plan=None,
            )
        return decision.model_dump_json(), 1, 0.0


