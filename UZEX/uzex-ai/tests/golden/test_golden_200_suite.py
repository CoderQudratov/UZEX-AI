@pytest.mark.anyio
async def test_category_l_infrastructure(shared_engine: QueryExecutor):
    """Verify health, read-only mode, and infrastructure boundaries."""
    import duckdb
    from httpx import ASGITransport, AsyncClient

    from app.api.application import create_app

    settings = Settings(database_path=Path("data/processed/uzex.duckdb"))
    app = create_app(settings)

    async with AsyncClient(transport=ASGITransport(app=app), base_url="http://test") as client:
        # L01, L02: GET /health returns 200 in < 10ms
        resp = await client.get("/health")
        assert resp.status_code == 200
        assert resp.json() == {"status": "ok"}

        # L05: GET /api/v1/status returns operational JSON
        st_resp = await client.get("/api/v1/status")
        assert st_resp.status_code == 200
        data = st_resp.json()
        assert data["status"] == "ready"
        assert data["warehouse_ready"] is True
        assert data["dataset_version"] is not None

    # L06, L07: DuckDB connection is strictly read-only and forbids write
    with shared_engine.warehouse.connection() as lease:
        with pytest.raises((duckdb.PermissionException, duckdb.CatalogException, duckdb.Error)):
            lease.execute("INSERT INTO deals (deal_id) VALUES (999999999)")
